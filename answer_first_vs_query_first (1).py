"""## Step 8: The comparison

**How to read it**
- *Usable examples*: training examples that ended with a verified, working chain of steps.
- *Tool tries*: how many times a tool was actually run. In a real company each of these could be a real system call that costs time and money.
- *Failed tool tries*: tries that produced an error. These are **not** directly comparable: in answer-first a failed try costs one cheap step (it is simply not added), while in query-first a failed search can sink a whole question.
- *Examples thrown away*: examples that never produced a verified chain. This is the waste the article is about.
- *AI calls*: how often the AI was asked to write. Answer-first uses the AI once per example, so it can use **more** AI calls; the saving shown here is in wasted tool tries and discarded examples.
"""

