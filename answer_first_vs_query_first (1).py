"""## Step 5: The tools (the "real systems" the agent can use)

These are small, real look-ups over **your** table. Each one can **succeed or fail**, just like a real business system:

| Tool | What it does | Fails when... |
|---|---|---|
| `find_invoices` | Finds all items of one customer | The customer does not exist |
| `keep_paid` | Keeps only items that were paid | None were paid |
| `keep_open` | Keeps only items still unpaid | None are open |
| `add_days_late` | Works out days between due date and payment | Some items are unpaid (no payment date yet) |
| `keep_late` | Keeps only items paid after the due date | Days late were not worked out first, or none are late |
| `count_rows` | Counts the items | (almost never) |
| `sum_amount` | Adds up the amounts | (almost never) |
| `average_days_late` | Average days between due date and payment | Days late were not worked out first |

The first five **prepare** the data. The last three **produce an answer**.
"""

class ToolError(Exception):
    pass

def new_state():
    return {"rows": None, "flags": set(), "answer": None}

def copy_state(s, **changes):
    # Any preparation step makes an earlier answer out of date, so the answer is cleared unless a tool sets a new one.
    n = {"rows": s["rows"], "flags": set(s["flags"]), "answer": None}
    n.update(changes)
    return n

def need_rows(s):
    if s["rows"] is None:
        raise ToolError(f"no {ITEM_WORD}s loaded yet: find the {ENTITY_WORD} first")
    return s["rows"]

def t_find(s, customer):
    rows = data[data.id == str(customer)]
    if rows.empty:
        raise ToolError(f"no {ITEM_WORD}s found for {ENTITY_WORD} {customer}")
    return copy_state(new_state(), rows=rows), f"{len(rows)} {ITEM_WORD}s found"

def t_keep_paid(s):
    rows = need_rows(s)
    rows = rows[rows.paid.notna()]
    if rows.empty:
        raise ToolError(f"none of the {ITEM_WORD}s are paid")
    return copy_state(s, rows=rows, flags=s["flags"] | {"paid"}), f"{len(rows)} paid"

def t_keep_open(s):
    rows = need_rows(s)
    rows = rows[rows.paid.isna()]
    if rows.empty:
        raise ToolError(f"no open {ITEM_WORD}s")
    return copy_state(s, rows=rows, flags=s["flags"] | {"open"}), f"{len(rows)} still open"

def t_add_days_late(s):
    rows = need_rows(s)
    if rows.paid.isna().any():
        raise ToolError(f"some {ITEM_WORD}s are unpaid, so days late cannot be worked out")
    rows = rows.assign(days_late=(rows.paid - rows.due).dt.days)
    return copy_state(s, rows=rows, flags=s["flags"] | {"days_late"}), "days late worked out"

def t_keep_late(s):
    rows = need_rows(s)
    if "days_late" not in rows.columns:
        raise ToolError("days late have not been worked out yet")
    rows = rows[rows.days_late > 0]
    if rows.empty:
        raise ToolError(f"no late {ITEM_WORD}s")
    return copy_state(s, rows=rows, flags=s["flags"] | {"late"}), f"{len(rows)} paid late"

def make_answer(s, measure, value):
    # Remembers WHICH filters were switched on at the moment of measuring, so the answer can be checked honestly.
    return {"measure": measure, "value": value, "flags": frozenset(s["flags"])}

def t_count(s):
    rows = need_rows(s)
    return copy_state(s, answer=make_answer(s, "count", int(len(rows)))), f"count = {len(rows)}"

def t_sum(s):
    rows = need_rows(s)
    total = float(rows.amount.sum())
    return copy_state(s, answer=make_answer(s, "total_amount", total)), f"total amount = {total:,.2f}"

def t_avg_days_late(s):
    rows = need_rows(s)
    if "days_late" not in rows.columns:
        raise ToolError("days late have not been worked out yet")
    avg = float(rows.days_late.mean())
    return copy_state(s, answer=make_answer(s, "avg_days_late", avg)), f"average days after due date = {avg:.1f}"

TOOLS = {
    "find_invoices":     {"fn": t_find,          "kind": "start",   "desc": f"find all {ITEM_WORD}s of one {ENTITY_WORD}"},
    "keep_paid":         {"fn": t_keep_paid,     "kind": "prepare", "desc": f"keep only paid {ITEM_WORD}s"},
    "keep_open":         {"fn": t_keep_open,     "kind": "prepare", "desc": f"keep only open {ITEM_WORD}s"},
    "add_days_late":     {"fn": t_add_days_late, "kind": "prepare", "desc": "work out days between due date and payment"},
    "keep_late":         {"fn": t_keep_late,     "kind": "prepare", "desc": f"keep only {ITEM_WORD}s paid after the due date"},
    "count_rows":        {"fn": t_count,         "kind": "measure", "desc": f"count the {ITEM_WORD}s"},
    "sum_amount":        {"fn": t_sum,           "kind": "measure", "desc": "add up the amounts"},
    "average_days_late": {"fn": t_avg_days_late, "kind": "measure", "desc": "average days between due date and payment"},
}

def run_tool(name, state, counter, **args):
    # Really runs a tool and keeps score. Returns (new_state, note) or (None, error message).
    counter["tool_tries"] += 1
    try:
        return TOOLS[name]["fn"](state, **args)
    except ToolError as e:
        counter["failed_tries"] += 1
        return None, str(e)

def new_counter():
    return {"tool_tries": 0, "failed_tries": 0, "ai_calls": 0, "ai_fallbacks": 0}

def describe_answer(state):
    a = state["answer"]
    if a["measure"] == "count":         return f"{a['value']:,} {ITEM_WORD}s"
    if a["measure"] == "total_amount":  return f"total {a['value']:,.2f}"
    return f"{a['value']:.1f} days on average after the due date"

print("Tools ready:", ", ".join(TOOLS))

"""## Step 6: Query-first (the traditional way)

1. **A question is written first.** The question writer does *not* know what data or tools exist, so, just like in real life, some questions **cannot** be answered from this table (for example *"who is the account manager?"* when no such column exists). That is the point of the exercise, and you can see the list in `TOPICS` below.
2. **Then a blind search hunts for steps that answer it.** It tries tools in random order, one after another, and backs up when a step fails. This is a simplified stand-in for the depth-first search mentioned in the article.
3. **If the search runs out of its budget, the example is thrown away.** All the effort spent on it is wasted.

*Note:* about 4 in 9 topics below are deliberately unanswerable. Change `TOPICS` and you change the gap between the two methods. That is why the numbers are an illustration and not a finding.
"""

# What executives might ask. "goal" says what a correct chain of steps must have produced.
# The goal is checked against the answer AND the filters that were switched on when it was measured,
# so a chain that counts first and filters afterwards does not count as a correct answer.
# goal = None means this table simply cannot answer the question.
TOPICS = [
    {"key": "late_count",   "ask": f"how many of the {ENTITY_WORD}'s paid {ITEM_WORD}s were paid late",
     "goal": lambda s: bool(s["answer"]) and s["answer"]["measure"] == "count" and "late" in s["answer"]["flags"]},
    {"key": "late_amount",  "ask": f"the total value of the {ENTITY_WORD}'s {ITEM_WORD}s that were paid late",
     "goal": lambda s: bool(s["answer"]) and s["answer"]["measure"] == "total_amount" and "late" in s["answer"]["flags"]},
    {"key": "avg_days",     "ask": f"on average, how many days after the due date the {ENTITY_WORD} pays",
     "goal": lambda s: bool(s["answer"]) and s["answer"]["measure"] == "avg_days_late" and "late" not in s["answer"]["flags"]},
    {"key": "open_total",   "ask": f"the total amount the {ENTITY_WORD} still owes on open {ITEM_WORD}s",
     "goal": lambda s: bool(s["answer"]) and s["answer"]["measure"] == "total_amount" and "open" in s["answer"]["flags"]},
    {"key": "paid_count",   "ask": f"how many {ITEM_WORD}s the {ENTITY_WORD} has already paid",
     "goal": lambda s: bool(s["answer"]) and s["answer"]["measure"] == "count" and "paid" in s["answer"]["flags"] and "late" not in s["answer"]["flags"]},
    # ---- questions this table cannot answer (no such data, no such tool) ----
    {"key": "contact",      "ask": f"who to contact at the {ENTITY_WORD} about overdue {ITEM_WORD}s", "goal": None},
    {"key": "credit_limit", "ask": f"what credit limit is set for the {ENTITY_WORD}",                  "goal": None},
    {"key": "manager",      "ask": f"which account manager owns the {ENTITY_WORD}'s account",          "goal": None},
    {"key": "region_rank",  "ask": f"how the {ENTITY_WORD} ranks against other {ENTITY_WORD}s in its region", "goal": None},
]

def blind_search(goal, customer, counter, budget=SEARCH_BUDGET, max_depth=6):
    # Tries tools in random order; backs up when something fails; gives up when the budget is used.
    used = {"n": 0}
    start, _ = run_tool("find_invoices", None, counter, customer=customer)
    used["n"] += 1
    if start is None:
        return None, used["n"]

    def go(state, chain):
        if goal(state):
            return chain, state
        if len(chain) >= max_depth:
            return None
        options = [n for n in TOOLS if n != "find_invoices" and n not in chain]
        random.shuffle(options)
        for name in options:
            if used["n"] >= budget:
                return None
            used["n"] += 1
            new_state_, _note = run_tool(name, state, counter)
            if new_state_ is None:
                continue
            found = go(new_state_, chain + [name])
            if found is not None:
                return found
        return None

    found = go(start, [])
    if found is None:
        return None, used["n"]
    chain, final_state = found
    return {"chain": ["find_invoices"] + chain, "state": final_state}, used["n"]

def run_query_first(customers):
    counter = new_counter()
    topics = random.choices(TOPICS, k=len(customers))

    # 1) The AI writes one question per (topic, customer) pair, in a single call.
    listing = "\n".join(f"{i+1}. {t['ask']} - for {ENTITY_WORD} number {c}" for i, (t, c) in enumerate(zip(topics, customers)))
    prompt = (
        f"You write questions that business executives might ask a data assistant about a table of {ITEM_WORD}s. "
        f"For each numbered item write ONE natural question (under 25 words) that asks for that thing and mentions the "
        f"{ENTITY_WORD} number. Return JSON exactly like {{\"questions\": [\"...\", \"...\"]}} with one question per item, in the same order.\n\n{listing}"
    )
    reply = ai_or_none(prompt, counter)
    questions = None
    if reply and isinstance(reply.get("questions"), list) and len(reply["questions"]) == len(customers):
        questions = [str(q) for q in reply["questions"]]
    if questions is None:
        questions = [f"For {ENTITY_WORD} {c}: {t['ask']}?" .capitalize() for t, c in zip(topics, customers)]

    # 2) A blind search tries to find steps that answer each question.
    results = []
    for q, t, c in zip(questions, topics, customers):
        if t["goal"] is None:
            # The search does not know the question is unanswerable, so it tries anyway and uses up its budget.
            found, tries = blind_search(lambda s: False, c, counter)
        else:
            found, tries = blind_search(t["goal"], c, counter)
        results.append({"question": q, "topic": t["key"], "customer": c, "found": found, "tries": tries})
    return results, counter

random.seed(SEED)
EXAMPLE_CUSTOMERS = [random.choice(POOL) for _ in range(NUM_EXAMPLES)]

print(f"Running query-first on {NUM_EXAMPLES} questions ... (this can take a minute)")
qf_results, qf_counter = run_query_first(EXAMPLE_CUSTOMERS)
qf_usable = sum(1 for r in qf_results if r["found"] is not None)
print(f"Done. Usable examples: {qf_usable} of {NUM_EXAMPLES}.  Tool tries: {qf_counter['tool_tries']}, failed: {qf_counter['failed_tries']}.")

"""## Step 7: Answer-first (the ToolGrad idea)

Here nothing is searched blindly. The example is **built one tested step at a time**, using the four parts named in the article:

| Part in the article | What it does here |
|---|---|
| **API Proposer** | Suggests three promising next tools (simple rule in this notebook; an AI in the real method) |
| **API Executors** | Really runs each suggested tool on the data and records what happened |
| **API Selector** | Looks at the real results, throws away the ones that failed, keeps a working one (simple rule here; the real method also gives written "directional feedback") |
| **LLM Updater** | Once the chain is verified, the AI writes the question that the chain answers |

Because every step is tested before it is accepted, a failing step is discarded **immediately**, instead of after a whole attempt has been wasted. If an example reaches a dead end, it steps back one verified step and avoids that tool.

*Fairness note:* both methods are equally "naive" about which tool to try next (random choice). The difference this notebook tests is the **order**: searching for steps after a question exists, versus verifying steps first.
"""

def run_answer_first(customers):
    counter = new_counter()
    examples = []

    for customer in customers:
        state, note = run_tool("find_invoices", None, counter, customer=customer)
        if state is None:
            examples.append(None); continue
        steps = [{"tool": "find_invoices", "result": note, "rejected": []}]
        states = [state]            # the verified state after each accepted step
        banned = set()              # tools that led this example into a dead end
        stuck = 0
        finished = False

        for _ in range(14):
            used = {s_["tool"] for s_ in steps}
            # API Proposer: suggest up to 3 tools. Answer-producing tools are only allowed after 2 preparation steps.
            pool = [n for n, t in TOOLS.items()
                    if n not in used and n not in banned and (t["kind"] != "measure" or len(steps) >= 3)]
            if not pool:
                if len(steps) > 1:                        # dead end: step back and avoid that tool
                    banned.add(steps.pop()["tool"]); states.pop(); continue
                break
            proposals = random.sample(pool, min(3, len(pool)))

            # API Executors: really run each proposal on the last verified state.
            outcomes = {name: run_tool(name, states[-1], counter) for name in proposals}

            # API Selector: keep only steps that really worked; finish as soon as an answer-producing tool works.
            good = [n for n in proposals if outcomes[n][0] is not None]
            if not good:
                stuck += 1
                if stuck >= 2 and len(steps) > 1:         # two empty rounds in a row: step back
                    banned.add(steps.pop()["tool"]); states.pop(); stuck = 0
                continue
            stuck = 0
            finishing = [n for n in good if TOOLS[n]["kind"] == "measure"]
            pick = finishing[0] if finishing else good[0]
            rejected = [(n, outcomes[n][1]) for n in proposals if n not in good]

            states.append(outcomes[pick][0])
            steps.append({"tool": pick, "result": outcomes[pick][1], "rejected": rejected})
            if TOOLS[pick]["kind"] == "measure":
                finished = True
                break

        if not finished:
            examples.append(None); continue
        state = states[-1]

        # LLM Updater: write the question that this verified chain answers.
        trace = "\n".join(f"- {TOOLS[s_['tool']]['desc']}  ->  {s_['result']}" for s_ in steps)
        prompt = (
            f"Below is a verified sequence of steps that was really run on a table of {ITEM_WORD}s for {ENTITY_WORD} number {customer}, "
            f"with the results.\n\n{trace}\n\nWrite ONE natural question (under 25 words), in plain business language, that an "
            f"executive could have asked and that these exact steps answer. Mention the {ENTITY_WORD} number. Do not mention steps or tools. "
            f"Return JSON exactly like {{\"question\": \"...\"}}"
        )
        reply = ai_or_none(prompt, counter)
        question = str(reply["question"]) if reply and "question" in reply else template_question(state, customer)
        examples.append({"question": question, "steps": steps, "state": state, "customer": customer})

    return examples, counter

def template_question(state, customer):
    # Used only when the AI is off or fails. Built from what the verified steps actually did.
    a = state["answer"]
    flags = a["flags"]
    scope = "paid late" if "late" in flags else ("still open" if "open" in flags else "paid")
    if a["measure"] == "avg_days_late":
        return f"On average, how many days after the due date does {ENTITY_WORD} {customer} pay?"
    if a["measure"] == "total_amount":
        return f"What is the total value of {ENTITY_WORD} {customer}'s {ITEM_WORD}s that are {scope}?"
    return f"How many of {ENTITY_WORD} {customer}'s {ITEM_WORD}s are {scope}?"

random.seed(SEED + 1)
