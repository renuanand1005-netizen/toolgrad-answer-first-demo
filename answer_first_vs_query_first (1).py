def parse_json(text):
    text = text.strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.lower().startswith("json"):
            text = text[4:]
    return json.loads(text)

def call_llm(prompt, counter=None, retries=4):
    # Asks the AI for a JSON answer and returns it as a Python object.
    if PROVIDER == "none":
        raise RuntimeError("AI is switched off")
    key = get_key()
    last_problem = ""
    for attempt in range(retries):
        time.sleep(PAUSE_SECONDS)
        if PROVIDER == "gemini":
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{MODEL_NAME}:generateContent"
            r = requests.post(
                url,
                headers={"x-goog-api-key": key, "Content-Type": "application/json"},
                json={"contents": [{"parts": [{"text": prompt}]}],
                      "generationConfig": {"temperature": 0.7, "responseMimeType": "application/json"}},
                timeout=90,
            )
        else:  # groq
            r = requests.post(
                "https://api.groq.com/openai/v1/chat/completions",
                headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"},
                json={"model": MODEL_NAME, "temperature": 0.7,
                      "response_format": {"type": "json_object"},
                      "messages": [{"role": "user", "content": prompt}]},
                timeout=90,
            )
        if r.status_code in (429, 500, 503):      # busy or rate-limited: wait and retry
            last_problem = f"{r.status_code} (busy / rate limit)"
            time.sleep(10 * (attempt + 1))
            continue
        if r.status_code != 200:
            raise RuntimeError(f"AI service returned {r.status_code}: {r.text[:300]}")
        body = r.json()
        if PROVIDER == "gemini":
            text = body["candidates"][0]["content"]["parts"][0]["text"]
        else:
            text = body["choices"][0]["message"]["content"]
        if counter is not None:
            counter["ai_calls"] += 1
        return parse_json(text)
    raise RuntimeError(f"AI kept replying with {last_problem}. Try again in a minute or raise PAUSE_SECONDS.")

