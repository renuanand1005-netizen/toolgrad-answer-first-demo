def rerun_search(results, budget):
    counter = new_counter()
    ok = 0
    for r in results:
        topic = next(t for t in TOPICS if t["key"] == r["topic"])
        goal = topic["goal"] or (lambda s: False)
        found, tries = blind_search(goal, r["customer"], counter, budget=budget)
        ok += found is not None
    return ok, counter["tool_tries"]

